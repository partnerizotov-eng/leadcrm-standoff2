def get_active_tour():
    """Тур для текущей страницы, если менеджер его ещё не видел — иначе None."""
    manager_id = session.get("manager_id")
    if not manager_id:
        return None
    tour = TOURS.get(request.endpoint)
    if not tour:
        return None
    seen = query_one(
        "SELECT id FROM manager_tours_seen WHERE manager_id=? AND tour_key=?",
        (manager_id, tour["key"]))
    if seen:
        return None
    return tour


def get_tour_for_replay():
    """Тур для текущей страницы независимо от того, просмотрен он или нет —
    для плавающей кнопки «Повторить обучение»."""
    if not session.get("manager_id"):
        return None
    return TOURS.get(request.endpoint)


@bp.route("/mark-seen", methods=["POST"])
def mark_seen():
    manager_id = session.get("manager_id")
    data = request.get_json(silent=True) or {}
    tour_key = data.get("tour_key")
    if not manager_id or not tour_key:
        return jsonify(ok=False), 400
    execute(
        "INSERT OR IGNORE INTO manager_tours_seen (manager_id, tour_key) VALUES (?, ?)",
        (manager_id, tour_key))
    return jsonify(ok=True)
